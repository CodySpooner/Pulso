"""Write a per-worktree `.env.local` so parallel Orca worktrees never collide.

Run it from the root of a linked worktree (Orca's setup hook does this):

    uv run python infra/scripts/worktree_env.py

Each worktree gets a slot N (1-15), derived from its path and unique among the repo's live
worktrees: API_PORT=8000+N, WEB_PORT=3000+N, REDIS_URL db N, and database pulso_<folder name>.
All worktrees share the one `pulso` dev compose stack (AGENTS.md section 6), so credentials and
hosts come from the worktree's `.env`. PULSO_SCHEDULER and COLLECTORS_LIVE are always off.
Settings load `.env.local` after `.env`. Stdlib only.
"""

import argparse
import hashlib
import re
import subprocess
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

SLOTS = range(1, 16)  # Redis ships 16 databases (0-15); slot 0 stays with the main checkout
DEFAULT_DATABASE_URL = "postgresql+psycopg://pulso@localhost:5432/pulso"
DEFAULT_REDIS_URL = "redis://localhost:6379/0"
HEADER = "# Generated by infra/scripts/worktree_env.py. Re-run it instead of editing.\n"


def read_env(path: Path) -> dict[str, str]:
    if not path.is_file():
        return {}
    env = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        key, sep, value = line.partition("=")
        if sep and not key.lstrip().startswith("#"):
            env[key.strip()] = value.strip().strip("'\"")
    return env


def derive(
    path: Path, base: dict[str, str], current: dict[str, str], siblings: list[dict[str, str]]
) -> dict[str, str]:
    """Env for the worktree at `path`.

    base: its `.env`; current: its existing `.env.local` (keeps the slot stable on re-runs);
    siblings: the `.env.local` files of the repo's other worktrees.
    """
    taken = {int(s["PULSO_WORKTREE_SLOT"]) for s in siblings if "PULSO_WORKTREE_SLOT" in s}
    slot = int(current.get("PULSO_WORKTREE_SLOT", 0))
    if slot not in SLOTS or slot in taken:
        start = int(hashlib.sha256(str(path).lower().encode()).hexdigest(), 16)
        probe_order = [SLOTS[(start + i) % len(SLOTS)] for i in range(len(SLOTS))]
        slot = next((s for s in probe_order if s not in taken), 0)
        if not slot:
            raise SystemExit("All 15 worktree slots are taken. Remove a stale worktree first.")

    slug = re.sub(r"[^a-z0-9]+", "_", path.name.lower()).strip("_")[:40] or "worktree"
    db_name = f"pulso_{slug}"
    if any(urlsplit(s.get("DATABASE_URL", "")).path == f"/{db_name}" for s in siblings):
        db_name += f"_{slot}"  # a worktree folder elsewhere has the same name

    db_url = urlsplit(base.get("DATABASE_URL") or DEFAULT_DATABASE_URL)._replace(path=f"/{db_name}")
    redis_url = urlsplit(base.get("REDIS_URL") or DEFAULT_REDIS_URL)._replace(path=f"/{slot}")
    web_port, api_port = 3000 + slot, 8000 + slot
    return {
        "PULSO_WORKTREE_SLUG": slug,
        "PULSO_WORKTREE_SLOT": str(slot),
        "API_PORT": str(api_port),
        "WEB_PORT": str(web_port),
        "API_URL": f"http://localhost:{api_port}",
        "CLERK_AUTHORIZED_PARTIES": f"http://localhost:{web_port}",
        "DATABASE_URL": urlunsplit(db_url),
        "REDIS_URL": urlunsplit(redis_url),
        "PULSO_SCHEDULER": "off",
        "COLLECTORS_LIVE": "off",
    }


def git(root: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(root), *args], capture_output=True, text=True, check=True
    ).stdout


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Write a per-worktree .env.local.")
    parser.add_argument("path", nargs="?", default=".", type=Path, help="worktree root")
    root = parser.parse_args(argv).path.resolve()

    git_dir, common_dir = git(
        root, "rev-parse", "--path-format=absolute", "--git-dir", "--git-common-dir"
    ).splitlines()
    if Path(git_dir) == Path(common_dir):
        raise SystemExit("This is the main checkout, not a linked worktree. Nothing written.")

    others = [
        Path(line.removeprefix("worktree "))
        for line in git(root, "worktree", "list", "--porcelain").splitlines()
        if line.startswith("worktree ")
    ]
    siblings = [read_env(p / ".env.local") for p in others if p.resolve() != root]
    base = read_env(root / ".env")
    if not base:
        print("warning: no .env here. Copy the main checkout's .env (never .env.collector).")

    env = derive(root, base, read_env(root / ".env.local"), siblings)
    body = HEADER + "".join(f"{key}={value}\n" for key, value in env.items())
    (root / ".env.local").write_text(body, encoding="utf-8", newline="\n")
    db_name = urlsplit(env["DATABASE_URL"]).path.lstrip("/")
    print(
        f"wrote .env.local: slot {env['PULSO_WORKTREE_SLOT']}, API_PORT {env['API_PORT']}, "
        f"WEB_PORT {env['WEB_PORT']}, database {db_name}, redis db {env['PULSO_WORKTREE_SLOT']}"
    )


if __name__ == "__main__":
    main()
